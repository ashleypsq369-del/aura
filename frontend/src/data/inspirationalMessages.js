/**
 * Get a random message (changes daily + with route/time variation)
 */
export function getDailyMessage(seed = Date.now()) {
  const idx = Math.floor((seed / 86400000) + seed) % MESSAGES.length;
  return MESSAGES[Math.abs(idx) % MESSAGES.length];
}

/**
 * Get N random messages starting from a given index
 */
export function getMessageSlice(startIdx, count = 5) {
  const msgs = [];
  for (let i = 0; i < count; i++) {
    msgs.push(MESSAGES[(startIdx + i) % MESSAGES.length]);
  }
  return msgs;
}
