import { motion } from 'framer-motion';
import { Heart, Activity, AlertCircle, CheckCircle } from 'lucide-react';

/**
 * Patient Risk Summary Component
 * Simplified, patient-friendly explanation of AI prediction
 * No technical jargon - plain language only
 * Gap Analysis Priority 1: Patient-facing AI Explain
 */
export default function PatientRiskSummary({ prediction }) {
  if (!prediction) {
    return (
      <div className="bg-[var(--card-bg)] rounded-lg p-6 shadow-md border-2 border-[var(--card-border)] text-center">
        <Heart className="w-12 h-12 text-[var(--text-400)] mx-auto mb-3" />
        <p className="text-[var(--text-600)]">No health insights available at this time</p>
      </div>
    );
  }

  const riskConfig = {
    'High': {
      color: 'red',
      icon: AlertCircle,
      emoji: '🔴',
      message: 'Your care team is closely monitoring your condition and will reach out soon.',
      advice: 'Please contact your care team immediately if you experience any concerning symptoms.'
    },
    'Moderate': {
      color: 'amber',
      icon: Activity,
      emoji: '🟡',
      message: 'Your health requires regular monitoring. Your care team is keeping track of your progress.',
      advice: 'Continue following your care plan and report any changes to your care team.'
    },
    'Low': {
      color: 'green',
      icon: CheckCircle,
      emoji: '🟢',
      message: 'Your condition is stable. Keep up the good work following your care plan!',
      advice: 'Continue with your current routine and attend scheduled appointments.'
    }
  };

  const config = riskConfig[prediction.risk_level] || riskConfig['Moderate'];
  const Icon = config.icon;

  // Extract plain language points from explanation
  const explanationPoints = prediction.plain_english_explanation
    ?.split('\n')
    .filter(line => line.trim().length > 0)
    .slice(0, 3) || [];

  return (
    <motion.div
      initial={{ opacity: 0, y: 20 }}
      animate={{ opacity: 1, y: 0 }}
      className={`bg-gradient-to-br from-${config.color}-50 to-white rounded-lg p-6 shadow-lg border-3 border-${config.color}-300`}
    >
      {/* Header */}
      <div className="flex items-center space-x-3 mb-4">
        <div className={`p-3 rounded-full bg-${config.color}-100`}>
          <Icon className={`w-8 h-8 text-${config.color}-600`} strokeWidth={2.5} />
        </div>
        <div>
          <h3 className="text-xl font-serif font-bold text-[var(--text-900)]">
            Your Health Status {config.emoji}
          </h3>
          <p className="text-sm text-[var(--text-600)]">Based on recent assessments</p>
        </div>
      </div>

      {/* Main Message */}
      <div className={`bg-[var(--card-bg)] rounded-lg p-4 mb-4 border-2 border-${config.color}-200`}>
        <p className="text-[var(--text-800)] font-medium leading-relaxed">
          {config.message}
        </p>
      </div>

      {/* Key Points */}
      {explanationPoints.length > 0 && (
        <div className="bg-[var(--card-bg)] rounded-lg p-4 mb-4 space-y-2">
          <h4 className="text-sm font-bold text-[var(--text-900)] mb-2">What This Means:</h4>
          {explanationPoints.map((point, idx) => (
            <div key={idx} className="flex items-start space-x-2">
              <span className={`text-${config.color}-600 font-bold mt-1`}>-</span>
              <p className="text-sm text-[var(--text-700)] flex-1">{point}</p>
            </div>
          ))}
        </div>
      )}

      {/* Advice */}
      <div className={`bg-${config.color}-100 rounded-lg p-4 border-2 border-${config.color}-300`}>
        <p className="text-sm font-semibold text-[var(--text-900)] mb-2">💡 What You Should Do:</p>
        <p className="text-sm text-[var(--text-700)]">{config.advice}</p>
      </div>

      {/* Disclaimer */}
      <div className="mt-4 pt-4 border-t-2 border-[var(--card-border)]">
        <p className="text-xs text-[var(--text-500)] text-center">
          This assessment is generated by AI to support your care team's decisions. 
          Always discuss any concerns with your healthcare provider.
        </p>
      </div>
    </motion.div>
  );
}
